PATTERNS_BY_CATEGORY: dict[str, tuple[list[str], float]] = {
    "sex": (SEX_PATTERNS, 1.0),
    "drugs": (DRUG_PATTERNS, 1.0),
    "smoking": (SMOKING_PATTERNS, 0.6),
    "alcohol": (ALCOHOL_PATTERNS, 0.6),
    "racism": (RACISM_PATTERNS, 1.0),
    "nationalism": (NATIONALISM_PATTERNS, 0.8),
    "fascism": (FASCISM_PATTERNS, 1.0),
    "violence": (VIOLENCE_PATTERNS, 0.9),
    "profanity": (PROFANITY_PATTERNS, 1.0),
}

_COMPILED: dict[str, tuple[re.Pattern, float]] = {}
for cat, (patterns, weight) in PATTERNS_BY_CATEGORY.items():
    combined = "|".join(patterns)
    _COMPILED[cat] = (re.compile(combined, re.IGNORECASE), weight)

CATEGORY_ORDER = [
    "racism", "fascism", "profanity", "sex",
    "drugs", "violence", "nationalism",
    "alcohol", "smoking",
]


def check_category(text: str, category: str) -> list[dict]:
    if category not in _COMPILED:
        return []
    regex, weight = _COMPILED[category]
    matches = []
    seen_spans: set[tuple[int, int]] = set()
    normalized = text.lower().replace("ё", "е")
    for m in regex.finditer(normalized):
        word = m.group()
        if word.lower() in WHITELIST:
            continue
        span = (m.start(), m.end())
        if span in seen_spans:
            continue
        seen_spans.add(span)
        matches.append({
            "start": m.start(),
            "end": m.end(),
            "word": word,
            "category": category,
            "severity": weight,
        })
    return matches


def check_all(text: str | None) -> dict:
    if not text or not text.strip():
        return {
            "hits": {}, "total_hits": 0, "total_weighted": 0.0,
            "categories": {}, "is_18plus": False, "has_red_flag": False,
            "word_count": 0, "density": 0.0,
        }
    word_count = len(re.findall(r"[\w']+", text, re.UNICODE))
    hits: dict[str, list[dict]] = {}
    total_hits = 0
    total_weighted = 0.0
    categories: dict[str, int] = {}
    is_18plus = False
    has_red_flag = False
    for cat in CATEGORY_ORDER:
        cat_matches = check_category(text, cat)
        if cat_matches:
            hits[cat] = cat_matches
            categories[cat] = len(cat_matches)
            total_hits += len(cat_matches)
            for m in cat_matches:
                total_weighted += m["severity"]
            is_18plus = True
            if cat in ("racism", "fascism"):
                has_red_flag = True
    density = total_hits / word_count if word_count > 0 else 0.0
    return {
        "hits": hits, "total_hits": total_hits,
        "total_weighted": round(total_weighted, 4),
        "categories": categories, "is_18plus": is_18plus,
        "has_red_flag": has_red_flag, "word_count": word_count,
        "density": round(density, 4),
    }
