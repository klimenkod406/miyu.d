"""Словарь нецензурной лексики с категориями и severity.

Категории:
  - severe   (1.0): классический мат, оскорбления — всегда explicit
  - moderate (0.6): грубая лексика, вульгаризмы — explicit с понижающим коэф.
  - mild     (0.3): жаргон, просторечия — учитывается слабо
  - slur     (1.0): расистские/гомофобные оскорбления — red-flag

Whitelist — слова, которые НЕ считаются матом несмотря на похожесть.
"""
from __future__ import annotations

# Псевдо-границы слов (чтобы не ловить "благо" в "бля")
_BL = r"(?<![а-яёa-zA-Z])"
_BR = r"(?![а-яёa-zA-Z])"


def _w(pattern: str) -> str:
    """Оборачивает паттерн границами слова."""
    return _BL + pattern + _BR


